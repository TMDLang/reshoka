def resolve_col_and_vol(folder_or_vol: Path) -> tuple[str, str]:
    """Return (col_name, vol_name) for either a song/0_book_info folder or a volume folder."""
    p = folder_or_vol.resolve()
    if p.parent == DOCS_ROOT.resolve():
        return p.name, p.name
    if p.parent.parent == DOCS_ROOT.resolve():
        if p.name == "0_book_info" or list(p.glob("*.tmd")):
            return p.parent.name, p.parent.name
        return p.parent.name, p.name
    return p.parent.parent.name, p.parent.name


def classify_song_section(
    col_name: str, vol_name: str, folder_name: str
) -> tuple[str | None, str | None, str]:
    """Return (year_heading, section_heading, number_label) for a song directory."""
    parts = folder_name.split("_")

    flat_formatter = FLAT_NUMBER_FORMATTERS.get(col_name)
    if flat_formatter is not None:
        return None, None, flat_formatter(folder_name, parts)

    if col_name == "kogakko_shokashu_1915":
        if len(parts) >= 2 and parts[0].isdigit() and parts[1].isdigit():
            cat, num = parts[0], f"({int(parts[1])})"
            return None, KOGAKKO_1915_SECTIONS.get(cat, f"第 {cat} 學年"), num
        return None, None, folder_name

    if (
        vol_name.startswith("koto_")
        and len(parts) >= 3
        and all(p.isdigit() for p in parts[:3])
    ):
        yr, cat, num = parts[0], parts[1], f"({int(parts[2])})"
        year_label = KOTO_YEARS.get(yr, "高等科 第二學年")
        sec_label = (
            KOTO_SPECIAL_SECTIONS.get((yr, cat))
            or KOTO_TERM_SECTIONS.get(cat)
            or f"單元 {cat}"
        )
        return year_label, sec_label, num

    if len(parts) >= 2 and parts[0].isdigit() and parts[1].isdigit():
        cat, num = parts[0], f"({int(parts[1])})"
        return None, SHINTEI_SECTIONS.get(cat, f"單元 {cat}"), num

    return None, None, folder_name
